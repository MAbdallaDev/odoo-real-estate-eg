#!/bin/sh
# Build the `19.0` branch the Odoo Apps store reads, from a ref of `main`.
#
# The store finds a module only in its own folder at the ROOT of the repository
# ("Each module needs to be in a separate folder at the root of the repository,
# even if there is only one module"), but here the module lives in
# addons/real_estate_eg/. So `19.0` is not a copy of `main`: it is generated,
# holding only
#   real_estate_eg/   the module, byte for byte as in addons/real_estate_eg/
#   LICENSE           the repository's licence
#   README.md         a pointer back to `main`
#
# Built with git plumbing from committed trees, so the working tree, the index
# and uncommitted changes are never read or touched. Each build is a new commit
# on top of the current `19.0`, so pushing it is a fast-forward.
#
# Usage: scripts/release_apps.sh [ref]       ref defaults to origin/main
#        DRY_RUN=1 scripts/release_apps.sh   build and show, push nothing
set -eu

remote="origin"
branch="19.0"
module="real_estate_eg"
ref="${1:-$remote/main}"

git fetch --quiet "$remote"

source_commit=$(git rev-parse --verify "$ref^{commit}")
module_tree=$(git rev-parse --verify "$source_commit:addons/$module")
license_blob=$(git rev-parse --verify "$source_commit:LICENSE")
version=$(git show "$source_commit:addons/$module/__manifest__.py" |
    sed -n 's/^ *"version": *"\([^"]*\)".*/\1/p')
short=$(git rev-parse --short "$source_commit")
repo_url=$(git config --get "remote.$remote.url" | sed 's#^git@github.com:#https://github.com/#; s#\.git$##')

readme_blob=$(git hash-object -w --stdin <<EOF
# $module — Odoo Apps build

This branch is **generated** for the Odoo Apps store. Do not commit here.

It holds the \`$module\` module at the repository root, where the store looks
for modules. It is rebuilt from \`main\` by \`make release-apps\`.

Source, tests, documentation and issues: $repo_url

Built from \`main\` at \`$short\`, module version \`$version\`.
EOF
)

root_tree=$(printf '100644 blob %s\tLICENSE\n100644 blob %s\tREADME.md\n040000 tree %s\t%s\n' \
    "$license_blob" "$readme_blob" "$module_tree" "$module" | git mktree)

if parent=$(git rev-parse --verify --quiet "refs/remotes/$remote/$branch"); then
    if [ "$(git rev-parse "$parent^{tree}")" = "$root_tree" ]; then
        echo "release_apps: $branch already matches $short (version $version); nothing to push."
        exit 0
    fi
    set -- -p "$parent"
else
    set --
fi

commit=$(git commit-tree "$root_tree" "$@" -m "Odoo Apps build of $short, version $version

Generated by scripts/release_apps.sh from main at $source_commit:
addons/$module/ placed at the repository root, with LICENSE and a README.")

echo "release_apps: built $(git rev-parse --short "$commit") from main at $short (version $version):"
git ls-tree --name-only "$commit"

if [ "${DRY_RUN:-0}" = "1" ]; then
    echo "release_apps: DRY_RUN=1, nothing pushed."
    exit 0
fi

git push --quiet "$remote" "$commit:refs/heads/$branch"
echo "release_apps: pushed $branch. Now press Scan on the repository in the Odoo Apps dashboard."
